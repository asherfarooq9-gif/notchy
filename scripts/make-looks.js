// Writes renderer/looks.css from lib/themes.js, so the colors of every look live in one place.
// Run it after changing lib/themes.js:  node scripts/make-looks.js   (a test fails if the file is out of date)
const fs = require('fs');
const path = require('path');
const { THEME_INFO } = require('../lib/themes');

const FILE = path.join(__dirname, '..', 'renderer', 'looks.css');

const wash = `--wash:
    radial-gradient(70% 55% at 10% 0%, color-mix(in srgb, var(--hue-a) var(--wash-a), transparent), transparent 70%),
    radial-gradient(60% 60% at 100% 100%, color-mix(in srgb, var(--hue-b) var(--wash-b), transparent), transparent 72%);`;

function build() {
  const classic = THEME_INFO.find((t) => t.id === 'classic');
  const hues = (t) => `--hue-a: ${t.a}; --hue-b: ${t.b}; --on-a: ${t.ink}; --a-text-light: ${t.textLight}; --a-text-dark: ${t.textDark};`;
  return `/* GENERATED by scripts/make-looks.js from lib/themes.js. Do not edit by hand.
   Two modes (light, dark) set the glass surfaces. A look sets two colors that tint everything.
   --accent       the look's color for text and icons, pushed darker or lighter per mode so it stays readable
   --accent-fill  the look's color for solid fills (buttons, selected day); --accent-ink sits on it
   --surface      frosted glass, --surface-solid is the same surface without see-through (used when transparency is off)
   Any element with data-theme wears that look's two colors (the look picker cards use this). The hero looks use only
   color palettes inspired by each character, never logos or official artwork. */
:root { ${hues(classic)} }
:root, [data-mode="light"] {
  color-scheme: light;
  --bg: #f2f2f7; --surface: rgba(255, 255, 255, .56); --surface-strong: rgba(255, 255, 255, .82); --surface-solid: #ffffff;
  --line: rgba(60, 60, 67, .16); --text: #1c1c1e; --muted: #5a5a62;
  --good: #1a7f37; --bad: #c62828; --hot: #c25100;
  --glass-hi: rgba(255, 255, 255, .95); --glass-edge: rgba(255, 255, 255, .72); --glass-lo: rgba(60, 60, 67, .08);
  --shadow: rgba(31, 31, 40, .16); --wash-a: 30%; --wash-b: 24%;
  --accent: var(--a-text-light); --accent-fill: var(--hue-a); --accent-ink: var(--on-a);
  --raised: var(--surface); --raised-2: var(--surface-strong);
  ${wash}
}
[data-mode="dark"] {
  color-scheme: dark;
  --bg: #0b0b0e; --surface: rgba(255, 255, 255, .07); --surface-strong: rgba(255, 255, 255, .13); --surface-solid: #1c1c22;
  --line: rgba(255, 255, 255, .13); --text: #f5f5f7; --muted: #a3a3ad;
  --good: #6ee7a0; --bad: #ff9aa2; --hot: #ffb347;
  --glass-hi: rgba(255, 255, 255, .24); --glass-edge: rgba(255, 255, 255, .12); --glass-lo: rgba(0, 0, 0, .35);
  --shadow: rgba(0, 0, 0, .55); --wash-a: 36%; --wash-b: 28%;
  --accent: var(--a-text-dark); --accent-fill: var(--hue-a); --accent-ink: var(--on-a);
  --raised: var(--surface); --raised-2: var(--surface-strong);
  ${wash}
}
${THEME_INFO.map((t) => `[data-theme="${t.id}"] { ${hues(t)} }`).join('\n')}
`;
}

if (require.main === module) {
  fs.writeFileSync(FILE, build());
  console.log('wrote', FILE);
}

module.exports = { build, FILE };
